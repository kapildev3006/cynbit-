"use client";

import React, { useState } from "react";
import { BlueprintOutput, WizardFormData } from "@/lib/schemas/blueprint";
import {
  Copy,
  Check,
  Printer,
  RotateCcw,
  Sparkles,
  Layers,
  Calendar,
  AlertTriangle,
  ArrowRight,
  ExternalLink,
} from "lucide-react";

interface Step4ResultProps {
  blueprint: BlueprintOutput;
  formData: WizardFormData;
  generatedBy: "llm" | "fallback" | "honeypot-mock";
  leadId?: string;
  onReset: () => void;
}

export function Step4Result({
  blueprint,
  formData,
  generatedBy,
  leadId,
  onReset,
}: Step4ResultProps) {
  const [copied, setCopied] = useState(false);

  const handleCopyMarkdown = async () => {
    const markdownContent = `# Cynbit AI Project Blueprint
**Generated For:** ${formData.name} (${formData.email}) ${formData.company ? `• ${formData.company}` : ""}
**Track:** ${formData.track}
**Timeline Target:** ${formData.timeline}
**Budget Range:** ${formData.budget}
**Date:** ${new Date().toLocaleDateString()}

---

## 1. Project Summary
${blueprint.projectSummary}

## 2. Recommended Cynbit Tech Stack
${blueprint.suggestedStack.map((tech) => `- ${tech}`).join("\n")}

## 3. Phased Implementation Roadmap
${blueprint.phases
  .map(
    (p) => `### ${p.phaseName} (${p.duration})
${p.deliverables.map((d) => `  - ${d}`).join("\n")}`
  )
  .join("\n\n")}

## 4. Key Architectural Risks & Open Questions
${blueprint.risksAndQuestions.map((q) => `- ${q}`).join("\n")}

## 5. Recommended Next Step
${blueprint.recommendedNextStep}

---
*Generated by Cynbit Technologies AI Project Blueprint Studio (cynbit.in)*
`;

    try {
      await navigator.clipboard.writeText(markdownContent);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch (err) {
      console.error("Clipboard copy failed:", err);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-8">
      {/* Action Header (hidden in print) */}
      <div className="no-print flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4 rounded-xl border border-cyan-500/30 bg-gradient-to-r from-cyan-950/40 to-slate-900/60 p-5 backdrop-blur-sm">
        <div>
          <div className="inline-flex items-center gap-2 text-xs font-mono font-medium text-cyan-400">
            <Sparkles className="h-3.5 w-3.5" />
            <span>Blueprint Generated Successfully</span>
            <span className="rounded bg-slate-800 px-1.5 py-0.5 text-[10px] uppercase text-slate-300">
              {generatedBy}
            </span>
          </div>
          <h2 className="mt-1 text-xl font-bold text-slate-100">
            Architectural Overview for {formData.company || formData.name}
          </h2>
          {leadId && (
            <p className="text-[11px] font-mono text-slate-400 mt-0.5">
              Ref ID: {leadId}
            </p>
          )}
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={handleCopyMarkdown}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-800/80 px-3.5 py-2 text-xs font-medium text-slate-200 transition hover:bg-slate-700 hover:text-white focus:outline-none focus:ring-2 focus:ring-cyan-400"
          >
            {copied ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-400" />
                <span className="text-emerald-300 font-semibold">Copied Markdown!</span>
              </>
            ) : (
              <>
                <Copy className="h-3.5 w-3.5" />
                <span>Copy Blueprint</span>
              </>
            )}
          </button>

          <button
            type="button"
            onClick={handlePrint}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-800/80 px-3.5 py-2 text-xs font-medium text-slate-200 transition hover:bg-slate-700 hover:text-white focus:outline-none focus:ring-2 focus:ring-cyan-400"
          >
            <Printer className="h-3.5 w-3.5" />
            <span>Print / PDF</span>
          </button>

          <button
            type="button"
            onClick={onReset}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-800 bg-slate-900 px-3.5 py-2 text-xs font-medium text-slate-400 transition hover:bg-slate-800 hover:text-slate-200 focus:outline-none focus:ring-2 focus:ring-slate-500"
          >
            <RotateCcw className="h-3.5 w-3.5" />
            <span>New Blueprint</span>
          </button>
        </div>
      </div>

      {/* Main Blueprint Document (Print-friendly container) */}
      <div className="print-container space-y-8 rounded-2xl border border-slate-800 bg-[#0b1120]/70 p-6 sm:p-8 backdrop-blur shadow-xl">
        {/* Print Only Header */}
        <div className="hidden print-only mb-6 border-b border-slate-300 pb-4">
          <div className="flex items-center justify-between">
            <div>
              <h1 className="text-2xl font-bold text-slate-900">
                Cynbit Technologies &bull; AI Project Blueprint
              </h1>
              <p className="text-xs text-slate-600">
                Prepared for: {formData.name} {formData.company ? `(${formData.company})` : ""} &bull; {formData.email}
              </p>
            </div>
            <div className="text-right text-xs text-slate-500 font-mono">
              cynbit.in
            </div>
          </div>
        </div>

        {/* Section 1: Executive Summary */}
        <section className="space-y-3">
          <div className="flex items-center gap-2 text-xs font-mono font-semibold uppercase tracking-wider text-cyan-400">
            <span className="flex h-5 w-5 items-center justify-center rounded bg-cyan-950/80 border border-cyan-800 text-[10px]">
              01
            </span>
            <span>Project Strategic Summary</span>
          </div>
          <p className="text-sm sm:text-base leading-relaxed text-slate-200 bg-slate-900/40 print-card p-4 rounded-xl border border-slate-800/80">
            {blueprint.projectSummary}
          </p>
        </section>

        {/* Section 2: Verified Cynbit Tech Stack */}
        <section className="space-y-3">
          <div className="flex items-center gap-2 text-xs font-mono font-semibold uppercase tracking-wider text-emerald-400">
            <span className="flex h-5 w-5 items-center justify-center rounded bg-emerald-950/80 border border-emerald-800 text-[10px]">
              02
            </span>
            <span>Suggested Production Tech Stack</span>
          </div>
          <div className="flex flex-wrap gap-2">
            {blueprint.suggestedStack.map((tech) => (
              <span
                key={tech}
                className="print-chip inline-flex items-center gap-1.5 rounded-lg border border-slate-700/80 bg-slate-900/80 px-3 py-1.5 font-mono text-xs font-medium text-slate-200 shadow-sm"
              >
                <Layers className="h-3 w-3 text-cyan-400" />
                {tech}
              </span>
            ))}
          </div>
        </section>

        {/* Section 3: Phased Roadmap & Deliverables */}
        <section className="space-y-3">
          <div className="flex items-center gap-2 text-xs font-mono font-semibold uppercase tracking-wider text-teal-400">
            <span className="flex h-5 w-5 items-center justify-center rounded bg-teal-950/80 border border-teal-800 text-[10px]">
              03
            </span>
            <span>Phased Implementation Roadmap</span>
          </div>
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {blueprint.phases.map((phase, idx) => (
              <div
                key={phase.phaseName}
                className="print-card flex flex-col justify-between rounded-xl border border-slate-800 bg-slate-900/50 p-4"
              >
                <div>
                  <div className="flex items-center justify-between text-xs text-slate-400 font-mono mb-2">
                    <span className="text-cyan-400 font-semibold">Phase {idx + 1}</span>
                    <span className="inline-flex items-center gap-1 text-slate-400">
                      <Calendar className="h-3 w-3" />
                      {phase.duration}
                    </span>
                  </div>
                  <h3 className="text-sm font-semibold text-slate-200">
                    {phase.phaseName}
                  </h3>
                  <ul className="mt-3 space-y-1.5 text-xs text-slate-400">
                    {phase.deliverables.map((item, dIdx) => (
                      <li key={dIdx} className="flex items-start gap-1.5">
                        <span className="mt-1 h-1.5 w-1.5 rounded-full bg-cyan-400 shrink-0" />
                        <span>{item}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              </div>
            ))}
          </div>
        </section>

        {/* Section 4: Risks and Open Questions */}
        <section className="space-y-3">
          <div className="flex items-center gap-2 text-xs font-mono font-semibold uppercase tracking-wider text-amber-400">
            <span className="flex h-5 w-5 items-center justify-center rounded bg-amber-950/80 border border-amber-800 text-[10px]">
              04
            </span>
            <span>Architectural Risks &amp; Open Questions</span>
          </div>
          <div className="rounded-xl border border-amber-500/20 bg-amber-950/10 print-card p-4">
            <ul className="space-y-2 text-xs sm:text-sm text-slate-300">
              {blueprint.risksAndQuestions.map((q, idx) => (
                <li key={idx} className="flex items-start gap-2">
                  <AlertTriangle className="h-4 w-4 shrink-0 text-amber-400 mt-0.5" />
                  <span>{q}</span>
                </li>
              ))}
            </ul>
          </div>
        </section>

        {/* Section 5: Recommended Next Step */}
        <section className="space-y-3">
          <div className="flex items-center gap-2 text-xs font-mono font-semibold uppercase tracking-wider text-emerald-400">
            <span className="flex h-5 w-5 items-center justify-center rounded bg-emerald-950/80 border border-emerald-800 text-[10px]">
              05
            </span>
            <span>Recommended Next Action</span>
          </div>
          <div className="rounded-xl border border-emerald-500/30 bg-emerald-950/20 print-card p-5">
            <p className="text-sm sm:text-base font-medium text-emerald-200 leading-relaxed">
              {blueprint.recommendedNextStep}
            </p>
            <div className="no-print mt-4 flex flex-wrap items-center gap-3">
              <a
                href="https://cynbit.in"
                target="_blank"
                rel="noreferrer"
                className="inline-flex items-center gap-1.5 rounded-lg bg-emerald-500 px-4 py-2 text-xs font-semibold text-slate-950 transition hover:bg-emerald-400"
              >
                Schedule Technical Discovery
                <ExternalLink className="h-3.5 w-3.5" />
              </a>
              <span className="text-xs text-slate-400 font-mono">
                Jaipur Studio &bull; Cynbit Technologies
              </span>
            </div>
          </div>
        </section>
      </div>

      {/* Footer reassurance */}
      <div className="no-print text-center text-xs text-slate-500">
        <p>
          Need to revise any requirement or explore another track? You can{" "}
          <button
            type="button"
            onClick={onReset}
            className="text-cyan-400 underline hover:text-cyan-300"
          >
            reset and re-run the wizard
          </button>
          .
        </p>
      </div>
    </div>
  );
}
